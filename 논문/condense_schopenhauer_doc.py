def add_page_number(section):
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    run._r.append(fld)


def parse_inline(paragraph, line):
    parts = re.split(r"(\*\*.*?\*\*|`.*?`)", line)
    for part in parts:
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            r = paragraph.add_run(part[2:-2])
            r.bold = True
        elif part.startswith("`") and part.endswith("`"):
            r = paragraph.add_run(part[1:-1])
            r.font.name = "Consolas"
            r._element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
        else:
            paragraph.add_run(part)


def build_docx(markdown):
    doc = Document()
    sec = doc.sections[0]
    sec.top_margin = Inches(1)
    sec.bottom_margin = Inches(1)
    sec.left_margin = Inches(1)
    sec.right_margin = Inches(1)
    add_page_number(sec)

    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Malgun Gothic"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Malgun Gothic")
    normal.font.size = Pt(10.5)
    normal.paragraph_format.line_spacing = 1.25
    normal.paragraph_format.space_after = Pt(7)

    for name, size, color, before, after in [
        ("Heading 1", 16, "2E74B5", 16, 8),
        ("Heading 2", 13, "2E74B5", 12, 6),
        ("Heading 3", 11.5, "1F4D78", 8, 4),
    ]:
        st = styles[name]
        st.font.name = "Malgun Gothic"
        st._element.rPr.rFonts.set(qn("w:eastAsia"), "Malgun Gothic")
        st.font.size = Pt(size)
        st.font.color.rgb = RGBColor.from_string(color)
        st.paragraph_format.space_before = Pt(before)
        st.paragraph_format.space_after = Pt(after)
        st.paragraph_format.keep_with_next = True

    body_started = False
    for raw in markdown.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("# "):
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_after = Pt(8)
            r = p.add_run(line[2:])
            r.bold = True
            r.font.name = "Malgun Gothic"
            r._element.rPr.rFonts.set(qn("w:eastAsia"), "Malgun Gothic")
            r.font.size = Pt(18)
            r.font.color.rgb = RGBColor.from_string("0B2545")
        elif line.startswith("## ") and not body_started and "어빈 얄롬" in line:
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_after = Pt(18)
            r = p.add_run(line[3:])
            r.font.name = "Malgun Gothic"
            r._element.rPr.rFonts.set(qn("w:eastAsia"), "Malgun Gothic")
            r.font.size = Pt(12)
            r.font.color.rgb = RGBColor.from_string("555555")
        elif line.startswith("## "):
            body_started = True
            doc.add_paragraph(line[3:], style="Heading 1")
        elif line.startswith("### "):
            body_started = True
            doc.add_paragraph(line[4:], style="Heading 2")
        else:
            body_started = True
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            parse_inline(p, line)

    doc.core_properties.title = "앎에서 앎의 해체로"
    doc.core_properties.subject = "10-13쪽 압축본"
    doc.core_properties.author = "Codex"
    doc.save(FINAL_DOCX)


